// Trains the merchant categorizer. Run: pnpm train:categorizer
//
// Builds the labelled merchant set, runs 4-fold cross-validation in which every shop or brand name
// is in exactly one fold (so each fold is tested on names the model never saw), picks the lowest
// confidence threshold that reaches 95% precision on the merchants the keyword rules cannot label,
// then trains on everything and writes packages/shared/src/ml/models/categorizer.ts.
import { writeFileSync } from "node:fs";
import {
  HASH_BUCKETS,
  MODEL_CLASSES,
  buildExamples,
  chooseThreshold,
  groupedCrossValidation,
  predictAll,
  statsAt,
  train,
  unitHash,
} from "../../packages/shared/src/index.ts";

const MIN_THRESHOLD = 0.9;
const OUT = new URL("../../packages/shared/src/ml/models/categorizer.ts", import.meta.url);
const examples = buildExamples();
const missed = examples.filter((e) => e.ruleMiss).length;
console.log(`${examples.length} labelled merchants; the keyword rules miss ${missed}.`);

// Names of known shop types (random split by full name): where the model is expected to work.
const key = (e) => `${e.counterparty}|${e.note}|${e.channel}`;
const test = examples.filter((e) => unitHash(key(e)) >= 0.8);
const known = chooseThreshold(
  test,
  predictAll(train(examples.filter((e) => unitHash(key(e)) < 0.8)), test),
  0.99,
);
// Shop types the model has never seen: precision stays near 50% at any threshold (see ML_REPORT.md),
// so the threshold is kept high and the AI fallback stays in place for those.
const oof = groupedCrossValidation(examples, 4);
const unseen = statsAt(examples, oof, MIN_THRESHOLD);
const chosen = { ...known, threshold: Math.max(known.threshold, MIN_THRESHOLD) };
console.log(
  `known shop types: ${known.threshold} reaches 99% precision (labels ${(known.coverage * 100).toFixed(0)}%). Never-seen shop types at ${MIN_THRESHOLD}: labels ${(unseen.coverage * 100).toFixed(1)}% at ${(unseen.precision * 100).toFixed(1)}% precision. Using ${chosen.threshold}.`,
);

const model = train(examples);
const round = (n) => Math.round(n * 100) / 100;
const weights = {
  version: 1,
  classes: MODEL_CLASSES,
  buckets: HASH_BUCKETS,
  bias: model.bias.map(round),
  weights: model.weights.map((row) => row.map(round)),
  threshold: chosen.threshold,
  trainedOn: `generated merchant set (${examples.length} names, seed 7); threshold: 99% precision on held-out names of known shop types, floored at 0.9 for shop types never seen`,
};
const rows = weights.weights.map((r) => `    [${r.join(",")}]`).join(",\n");
writeFileSync(
  OUT,
  `import type { CategorizerWeights } from "../categorize-model.ts";

/** Generated by scripts/ml/train-categorizer.mjs. Do not edit by hand. */
// prettier-ignore
export const CATEGORIZER_WEIGHTS: CategorizerWeights | null = {
  version: ${weights.version},
  classes: ${JSON.stringify(weights.classes)},
  buckets: ${weights.buckets},
  bias: ${JSON.stringify(weights.bias)},
  threshold: ${weights.threshold},
  trainedOn: ${JSON.stringify(weights.trainedOn)},
  weights: [
${rows},
  ],
};
`,
);
console.log(`wrote ${OUT.pathname}`);
