// Trains the ridge spend forecaster on simulated people. Run: pnpm train:forecast
//
// Generates a train and a validation population (different seeds), takes many forecast origins per
// person, and fits ridge regression on "spend on each of the next 30 days / the person's own mean
// spend". The regularisation strength is picked on the validation people. The final fit uses both.
// Output: packages/shared/src/ml/models/forecast-ridge.ts (numbers only, no data).
import { writeFileSync } from "node:fs";
import {
  FORECAST_FEATURE_NAMES,
  RidgeAccumulator,
  addForecastTrainingRows,
  addDays,
  dayDiff,
  dhakaDay,
  forecastCashflow,
  groupKey,
} from "../../packages/shared/src/index.ts";
import { buildUser, makePopulation } from "../../adapters/upay-sim/src/index.ts";

const TRAIN_USERS = Number(process.env.TRAIN_USERS ?? 450);
const VALIDATION_USERS = Number(process.env.VALIDATION_USERS ?? 150);
const HORIZON = 30;
const LAMBDAS = [0.1, 1, 10, 100, 1000];
const OUT = new URL("../../packages/shared/src/ml/models/forecast-ridge.ts", import.meta.url);

/** Adds every usable origin of one person; returns the number of rows added. */
function addUser(acc, user) {
  const { txs, spec } = user;
  let rows = 0;
  // Origins every 7 days, from 30 days of history up to the last day that still has 30 days after it.
  const last = addDays(spec.endDay, -HORIZON);
  const first = addDays(spec.endDay, -(spec.days - 1) + 30);
  for (let cut = first; cut <= last; cut = addDays(cut, 7)) {
    const known = txs.filter((t) => dhakaDay(t.occurred_at) <= cut);
    let captured = null;
    forecastCashflow({
      now: new Date(`${cut}T06:00:00Z`),
      balance: 0,
      transactions: known,
      horizonDays: HORIZON,
      spendPredictor: (input) => {
        captured ??= input;
        return null;
      },
    });
    if (!captured) continue;
    const keys = new Set(captured.recurring.map((r) => r.key));
    const actual = new Array(HORIZON).fill(0);
    for (const t of txs) {
      const d = dhakaDay(t.occurred_at);
      if (d <= cut || d > addDays(cut, HORIZON)) continue;
      if (t.direction === "out" && !keys.has(groupKey(t))) actual[dayDiff(cut, d) - 1] += t.amount;
    }
    rows += addForecastTrainingRows(acc, captured, actual);
  }
  return rows;
}

const build = (split, count) => {
  const acc = new RidgeAccumulator(FORECAST_FEATURE_NAMES.length);
  for (const spec of makePopulation(split, count)) addUser(acc, buildUser(spec));
  return acc;
};

console.log(
  `Building training rows (${TRAIN_USERS} train, ${VALIDATION_USERS} validation people)...`,
);
const train = build("train", TRAIN_USERS);
const validation = build("validation", VALIDATION_USERS);
console.log(`rows: train ${train.n}, validation ${validation.n}`);

let best = null;
for (const lambda of LAMBDAS) {
  const model = train.fit(lambda);
  if (!model) continue;
  const mse = validation.mse(model);
  console.log(`lambda ${String(lambda).padEnd(6)} validation MSE ${mse.toFixed(4)}`);
  if (!best || mse < best.mse) best = { lambda, mse };
}
if (!best) throw new Error("no ridge fit succeeded");

const all = new RidgeAccumulator(FORECAST_FEATURE_NAMES.length);
all.merge(train);
all.merge(validation);
const final = all.fit(best.lambda);
const round = (n) => Math.round(n * 1e6) / 1e6;
const weights = {
  version: 1,
  featureNames: FORECAST_FEATURE_NAMES,
  intercept: round(final.intercept),
  coef: final.coef.map(round),
  lambda: best.lambda,
  trainedOn: `simulated people: ${TRAIN_USERS} train + ${VALIDATION_USERS} validation (seeds train-0.., validation-0..), ${all.n} rows, 30-day horizon`,
};

writeFileSync(
  OUT,
  `import type { RidgeForecastWeights } from "../forecast-ridge.ts";

/** Generated by scripts/ml/train-forecast.mjs. Do not edit by hand. */
export const FORECAST_RIDGE_WEIGHTS: RidgeForecastWeights | null = ${JSON.stringify(weights, null, 2)};
`,
);
console.log(`chosen lambda ${best.lambda}; wrote ${OUT.pathname}`);
